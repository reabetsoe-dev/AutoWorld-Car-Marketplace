export function getPrimaryCarImage(car, index = 0) {
  return (
    car?.imageUrls?.[0] ||
    fallbackInventory[index % fallbackInventory.length]?.imageUrls?.[0] ||
    showroomImages.fallback
  );
}

export function getGalleryImages(car) {
  const seededImages = fallbackInventory.flatMap((item) => item.imageUrls).slice(0, 6);
  const images = car?.imageUrls?.length ? car.imageUrls : seededImages;
  return [...images, ...seededImages].slice(0, 6);
}

export function findFallbackCar(id) {
  return fallbackInventory.find((car) => car._id === id);
}
